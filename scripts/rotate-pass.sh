#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════
# Смена пароля приложения ОДНОЙ командой (приёмка ТЗ-1, 29.08.2026).
#
#     cd ~/mihizumov-healthbook/uspeyu-kontur && ./scripts/rotate-pass.sh
#
# Фраза спрашивается вслепую (не видна на экране, не попадает в историю
# шелла и в argv процессов). Дальше скрипт сам: хеш → src/config.js →
# перешифровка данных → дымовой тест → коммит.
#
# ⚠ Почему не одной строкой с фразой в аргументе: аргументы видны в
#   `ps` и истории; фраза, засветившаяся хоть где-то, — уже не фраза.
# ═══════════════════════════════════════════════════════════════════════
set -euo pipefail
cd "$(dirname "$0")/.."

command -v node >/dev/null || { echo "⛔ node не найден"; exit 1; }
test -f src/config.js || { echo "⛔ запускать из uspeyu-kontur/"; exit 1; }

printf "Новая фраза (ввод скрыт, минимум 12 символов): "
read -rs P1; echo
printf "Ещё раз: "
read -rs P2; echo

[ "$P1" = "$P2" ] || { echo "⛔ Фразы не совпали, ничего не изменено."; exit 1; }
[ ${#P1} -ge 12 ] || { echo "⛔ Короче 12 символов — перебирается по словарю. Ничего не изменено."; exit 1; }

# ⛔ ЗАЩИТА ОТ НЕВИДИМОЙ ОШИБКИ ВВОДА (30.08.2026).
#
# Ввод скрыт, поэтому кавычки, случайно попавшие в фразу, увидеть нечем — а
# попадают они легко: человек копирует из инструкции строку вида
# KONTUR_PASS='фраза', и апострофы едут вместе с текстом. По дороге через
# редактор или мессенджер прямые ' превращаются в типографские ‘ ’.
#
# *Повод:* ровно это и случилось 29.08. Настоящей фразой стало
# ‘…’ с кавычками по краям: локально всё работало (там она подставлялась
# так же), CI падал «пароль не совпадает», а на телефоне такую фразу не
# набрать вовсе — ‘ и ’ на клавиатуре нет. Искали в секрете GitHub.
case "$P1" in
  \'*|\"*|‘*|“*|*\'|*\"|*’|*”)
    echo "⛔ Фраза начинается или кончается кавычкой."
    echo "   Скорее всего они скопировались вместе с текстом команды."
    echo "   Введите фразу БЕЗ кавычек. Ничего не изменено."
    exit 1 ;;
esac
case "$P1" in
  *[!\ -~]*)
    echo "⛔ В фразе есть символы вне латиницы, цифр и знаков ASCII."
    echo "   Такую фразу не набрать на телефонной клавиатуре — вход станет"
    echo "   невозможен. Ничего не изменено."
    exit 1 ;;
esac


echo "→ считаю хеш и вписываю в src/config.js…"
HASH=$(printf '%s' "$P1" | node scripts/passcode.mjs | grep -oE '[0-9a-f]{64}' | head -1)
[ -n "$HASH" ] || { echo "⛔ passcode.mjs не вернул хеш"; exit 1; }

node -e "
const fs = require('fs');
let t = fs.readFileSync('src/config.js', 'utf8');
const re = /(PASSCODE_HASH =\s*\n?\s*')([0-9a-f]{64})(')/m;
// ⚠ ДВА РАЗНЫХ СЛУЧАЯ, КОТОРЫЕ РАНЬШЕ СЛИВАЛИСЬ В ОДИН.
//   Проверка была `next === t` → «PASSCODE_HASH не найден». Но текст не
//   меняется и тогда, когда новый хеш РАВЕН старому, то есть когда фраза
//   та же. 30.08.2026 это увело в сторону на полчаса: владелец вводил
//   верную фразу, скрипт отвечал «поле не найдено», и искали поломку в
//   config.js, которой не было. Настоящая рассинхронизация была в .enc.
const m = t.match(re);
if (!m) { console.error('⛔ PASSCODE_HASH в config.js не найден'); process.exit(1); }
if (m[2] === '$HASH') {
  console.log('  = PASSCODE_HASH уже такой — фраза не изменилась, config.js не трогаем');
} else {
  fs.writeFileSync('src/config.js', t.replace(re, '\$1$HASH\$3'));
  console.log('  ✓ PASSCODE_HASH обновлён');
}
"

echo "→ перешифровываю данные той же фразой…"
KONTUR_PASS="$P1" npm run --silent data:encrypt

echo "→ дымовой тест…"
KONTUR_PASS="$P1" npm run --silent test | tail -1

unset P1 P2

git add src/config.js public/data/health.enc.json
git commit -q -m "Смена пароля: новый хеш + пересборка данных" || echo "  (коммитить нечего)"
echo ""
echo "✅ Готово. Фраза нигде не сохранена — запомните её."
echo "   Не забудьте: тот же текст пойдёт в секрет KONTUR_PASS на GitHub."
